/** 분기 해석문. 역방향이면 마지막 문장을 역방향 주의점으로 바꾼다. */
export function getQuarterText(cardId, q, reversed) {
  const text = NEWYEAR_CARD_INTERPRETATIONS[cardId]?.[q]?.text ?? ''
  if (!reversed || !NEWYEAR_REVERSED_NOTES[cardId]) return text
  const sentences = text.split(/(?<=요\.)\s+/)
  return [...sentences.slice(0, -1), NEWYEAR_REVERSED_NOTES[cardId]].join(' ')
}

// ── 연간 카드 ─────────────────────────────────────────────────────────────
// 생일(월·일)과 연도의 숫자를 모두 더해 22 이하가 될 때까지 자릿수를 다시 더한다(타로 Year Card).
// 22는 바보(0번). 연도가 필요 없으므로 생년은 받지 않는다.
const MAJOR_ORDER = [
  'fool', 'magician', 'priestess', 'empress', 'emperor', 'hierophant', 'lovers', 'chariot',
  'strength', 'hermit', 'wheel', 'justice', 'hanged', 'death', 'temperance', 'devil',
  'tower', 'star', 'moon', 'sun', 'judgement', 'world',
]

const digitSum = n => String(n).split('').reduce((a, d) => a + Number(d), 0)

export function isValidBirthday(month, day) {
  const m = Number(month)
  const d = Number(day)
  if (!Number.isInteger(m) || !Number.isInteger(d) || m < 1 || m > 12 || d < 1) return false
  return d <= new Date(2000, m, 0).getDate() // 윤년 기준이라 2월 29일 허용
}

/** @returns {number|null} 메이저 번호 0~21 */
export function getYearCardNumber(month, day, year = NEWYEAR_YEAR) {
  if (!isValidBirthday(month, day)) return null
  let n = digitSum(month) + digitSum(day) + digitSum(year)
  while (n > 22) n = digitSum(n)
  return n === 22 ? 0 : n
}

export function yearCardIdFromNumber(n) {
  return Number.isInteger(n) && n >= 0 && n <= 21 ? MAJOR_ORDER[n] : null
}

