const ENERGY_SCORE = { positive: 1, neutral: 0, challenging: -1 }

function getYearShape(scores) {
  const [s1, s2, s3, s4] = scores
  const firstHalf = s1 + s2
  const secondHalf = s3 + s4
  const total = firstHalf + secondHalf
  if (secondHalf - firstHalf >= 2) return 'rising'
  if (firstHalf - secondHalf >= 2) return 'falling'
  if (total >= 3) return 'bright'
  if (total <= -2) return 'heavy'
  if (scores.includes(1) && scores.includes(-1)) return 'wave'
  return 'steady'
}

/**
 * 신년 연애운 4장으로 한 해 요약 생성
 * @param {{ energy: string, reversed: boolean }[]} cards - q1~q4 순서
 * @param {string|null} status - single | situationship | dating | breakup
 */
export function getNewYearOverall(cards, status) {
  const scores = cards.map(c => Math.max(-1, (ENERGY_SCORE[c.energy] ?? 0) - (c.reversed ? 1 : 0)))
  const shape = YEAR_SHAPES[getYearShape(scores)]

  const max = Math.max(...scores)
  const min = Math.min(...scores)
  const peakIdx = scores.indexOf(max)
  const restIdx = scores.indexOf(min)
  const peakLabel = NEWYEAR_POSITION_LABELS[NEWYEAR_POSITIONS[peakIdx]]
  const restLabel = NEWYEAR_POSITION_LABELS[NEWYEAR_POSITIONS[restIdx]]

  const highlights = [max > 0
    ? `가장 빛나는 시기는 ${withJosa(peakLabel, '이에요', '예요')}. 마음먹은 일이 있다면 이때 움직여 보세요.`
    : `상대적으로 숨통이 트이는 시기는 ${withJosa(peakLabel, '이에요', '예요')}. 중요한 대화나 결정은 이때로 잡아보세요.`]
  if (min < max) {
    highlights.push(min < 0
      ? `${restLabel}에는 속도를 늦추고 마음을 돌보는 데 집중해 보세요.`
      : `${topic(restLabel)} 상대적으로 잔잔한 시기라, 다음을 준비하는 시간으로 쓰기 좋아요.`)
  }

  const guidance = STATUS_GUIDANCE[status] ?? null

  return {
    title: shape.title,
    summary: shape.summary,
    yearFlow: shape.yearFlow,
    highlights,
    peakLabel,
    peakBright: max > 0,
    statusTitle: guidance?.title ?? '',
    statusGuidance: guidance ? guidance.lines.map(l => l.replace('{peak}', peakLabel)) : [],
  }
}

